import { readdir, readFile, writeFile, mkdir } from 'node:fs/promises';
import { join } from 'node:path';

/**
 * TypeScript permits one wildcard per ambient module. Generate exact query suffixes
 * instead of an unsafe catch-all declaration that would hide unrelated import errors.
 */
export async function generateImageTypes(root: string): Promise<string> {
  const queries = new Set<string>();
  let scanned = 0;
  async function scan(directory: string): Promise<void> {
    for (const entry of await readdir(directory, { withFileTypes: true })) {
      if (
        entry.name.startsWith('.') ||
        ['node_modules', 'dist', 'build', 'coverage'].includes(entry.name)
      )
        continue;
      const path = join(directory, entry.name);
      if (entry.isDirectory()) {
        await scan(path);
        continue;
      }
      if (
        !/\.(?:svelte|[cm]?[jt]sx?)$/.test(entry.name) ||
        entry.name.endsWith('.d.ts') ||
        ++scanned > 5000
      )
        continue;
      const source = await readFile(path, 'utf8');
      const imports = source.matchAll(
        /(?:\bfrom\s*|\bimport\s*(?:\(\s*)?)["']([^"']+\?[^"']+)["']/g,
      );
      for (const match of imports) {
        const query = match[1]!.slice(match[1]!.indexOf('?'));
        if (new URLSearchParams(query.slice(1)).has('img')) queries.add(query);
      }
    }
  }
  await scan(root);
  const hasSrc = await readdir(root).then((entries) => entries.includes('src'));
  const directory = hasSrc ? join(root, 'src') : root;
  await mkdir(directory, { recursive: true });
  const output = join(directory, 'imageway-env.d.ts');
  const contents =
    '// Generated by svelte-imageway. Run the dev server or CLI init after changing image directives.\n' +
    [...queries]
      .sort()
      .map(
        (query) =>
          `declare module ${JSON.stringify(`*${query}`)} { const image: import('svelte-imageway').ImageArtifact; export default image; }`,
      )
      .join('\n') +
    '\n';
  if ((await readFile(output, 'utf8').catch(() => '')) !== contents)
    await writeFile(output, contents);
  return output;
}
