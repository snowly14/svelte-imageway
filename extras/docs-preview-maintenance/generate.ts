import { readFile, writeFile, readdir, mkdir, copyFile, stat } from 'node:fs/promises';
import { marked } from 'marked';
import { resolve, dirname } from 'node:path';
const entries: { slug: string; title: string; html: string }[] = [];
const sources = [
  ...(await readdir('docs/guides'))
    .filter((v) => v.endsWith('.md'))
    .map((v) => ({ slug: v.slice(0, -3), path: 'docs/guides/' + v })),
  { slug: 'url-contract', path: 'docs/spec/url-contract.md' },
  { slug: 'security', path: 'SECURITY.md' },
  { slug: 'topology-and-costs', path: 'docs/research/platforms-and-costs.md' },
];
for (const folder of ['adr', 'research'])
  for (const name of await readdir('docs/' + folder))
    if (name.endsWith('.md'))
      sources.push({ slug: folder + '-' + name.slice(0, -3), path: 'docs/' + folder + '/' + name });
const paths = new Map(sources.map((v) => [resolve(v.path), v.slug]));
for (const source of sources) {
  const md = await readFile(source.path, 'utf8');
  const title = md.match(/^# (.+)$/m)?.[1] ?? source.slug;
  entries.push({
    slug: source.slug,
    title,
    html: (await marked.parse(md))
      .replace(/^<h1>.*?<\/h1>\s*/, '')
      .replace(/href="([^"]+)"/g, (all, href: string) => {
        if (/^(?:https?:|#|mailto:)/.test(href)) return all;
        const [path, fragment] = href.split('#');
        const target = resolve(dirname(source.path), path!);
        const slug = paths.get(target);
        if (!slug && !href.startsWith('/'))
          return `href="/references/${target.slice(process.cwd().length + 1)}${fragment ? '#' + fragment : ''}"`;
        return slug ? `href="/docs/${slug}${fragment ? '#' + fragment : ''}"` : all;
      })
      .replace(
        /<h([2-6])>(.*?)<\/h\1>/g,
        (_all, depth: string, content: string) =>
          `<h${depth} id="${content
            .replace(/<[^>]+>/g, '')
            .toLowerCase()
            .replace(/[^a-z0-9]+/g, '-')
            .replace(/^-|-$/g, '')}">${content}</h${depth}>`,
      ),
  });
}
await mkdir('extras/docs-preview/src/lib/server', { recursive: true });
await writeFile(
  'extras/docs-preview/src/lib/server/articles.ts',
  '// Generated from repository Markdown by extras/docs-preview-maintenance/generate.ts.\nexport const articles = ' +
    JSON.stringify(entries, null, 2) +
    ';\n',
);
await writeFile(
  'extras/docs-preview/src/lib/navigation.ts',
  '// Generated by extras/docs-preview-maintenance/generate.ts.\nexport const navigation = ' +
    JSON.stringify(
      entries.map(({ slug, title }) => ({ slug, title })),
      null,
      2,
    ) +
    ';\n',
);

// Ship only explicit linked repository reference files, never directories or local state.
for (const article of entries)
  for (const match of article.html.matchAll(/href="\/references\/([^"#]+)"/g)) {
    const source = resolve(match[1]!);
    if (!source.startsWith(resolve('docs') + '/') && source !== resolve('REPORT.md'))
      throw new Error('Reference outside documentation');
    if (!(await stat(source)).isFile()) throw new Error('Expected reference file');
    const out = 'extras/docs-preview/static/references/' + match[1];
    await mkdir(dirname(out), { recursive: true });
    await copyFile(source, out);
  }
